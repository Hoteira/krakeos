use crate::arch::x86_64::io::{inb, outb};
use crate::println;

pub const MOUSE_INT: u8 = 44;
pub static mut MOUSE_PACKET: [u8; 4] = [0; 4];
pub static mut MOUSE_IDX: usize = 0;
pub static mut MOUSE_PACKET_SIZE: usize = 3;

const CMD_ENABLE_AUX: u8 = 0xA8;
const CMD_GET_COMPAQ_STATUS: u8 = 0x20;
const CMD_SET_COMPAQ_STATUS: u8 = 0x60;
const CMD_WRITE_AUX: u8 = 0xD4;

const MOUSE_RESET: u8 = 0xFF;
const MOUSE_SET_DEFAULTS: u8 = 0xF6;
const MOUSE_ENABLE_STREAMING: u8 = 0xF4;
const MOUSE_GET_ID: u8 = 0xF2;

pub fn init_mouse() {
    println!("Mouse: Initializing PS/2 Mouse...");

    wait_write();
    outb(0x64, CMD_ENABLE_AUX);

    wait_write();
    outb(0x64, CMD_GET_COMPAQ_STATUS);
    wait_read();
    let mut status = inb(0x60);
    status |= 2;
    status &= !0x20;
    wait_write();
    outb(0x64, CMD_SET_COMPAQ_STATUS);
    wait_write();
    outb(0x60, status);

    // Unmask IRQ 12 on slave PIC
    unsafe {
        (*(&raw const crate::arch::x86_64::pic::PICS)).slave.unmask_irq(4);
    }

    // Standard PS/2 Mouse Initialization
    mouse_write(MOUSE_SET_DEFAULTS);
    let _ack = mouse_read();

    // Try to enable scroll wheel (IntelliMouse sequence)
    mouse_write(0xF3); // Set Sample Rate
    let _ = mouse_read();
    mouse_write(200);
    let _ = mouse_read();
    mouse_write(0xF3); // Set Sample Rate
    let _ = mouse_read();
    mouse_write(100);
    let _ = mouse_read();
    mouse_write(0xF3); // Set Sample Rate
    let _ = mouse_read();
    mouse_write(80);
    let _ = mouse_read();

    mouse_write(MOUSE_GET_ID);
    let _ack = mouse_read();
    let id = mouse_read();

    unsafe {
        if id == 3 || id == 4 {
            MOUSE_PACKET_SIZE = 4;
        } else {
            MOUSE_PACKET_SIZE = 3;
        }
    }

    mouse_write(MOUSE_ENABLE_STREAMING);
    let _ack = mouse_read();

    println!("Mouse: Initialized (ID: {}).", id);
}

fn mouse_write(value: u8) {
    wait_write();
    outb(0x64, CMD_WRITE_AUX);
    wait_write();
    outb(0x60, value);
}

fn mouse_read() -> u8 {
    wait_read();
    inb(0x60)
}

fn wait_write() {
    let mut timeout = 100_000;
    while timeout > 0 {
        if (inb(0x64) & 2) == 0 { return; }
        timeout -= 1;
    }
}

fn wait_read() {
    let mut timeout = 100_000;
    while timeout > 0 {
        if (inb(0x64) & 1) == 1 { return; }
        timeout -= 1;
    }
}

