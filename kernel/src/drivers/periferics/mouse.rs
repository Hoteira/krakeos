use crate::drivers::port::{inb, outb};
use crate::println;

pub const MOUSE_INT: u8 = 44;
pub static mut MOUSE_PACKET: [u8; 4] = [0; 4];
pub static mut MOUSE_IDX: usize = 0;
pub static mut MOUSE_PACKET_SIZE: usize = 3;

pub static mut VMMOUSE_ACTIVE: bool = false;

const VMPORT_MAGIC: u32 = 0x564D5868;
const VMPORT_PORT: u16 = 0x5658;
pub const VMPORT_CMD_VMMOUSE_DATA: u32 = 39;
pub const VMPORT_CMD_VMMOUSE_STATUS: u32 = 40;
const VMPORT_CMD_VMMOUSE_COMMAND: u32 = 41;

const VMMOUSE_READ_ID: u32 = 0x45414552;
const VMMOUSE_REQUEST_ABSOLUTE: u32 = 0x53424152;

pub fn vmport_in(command: u32, mut ebx: u32) -> (u32, u32, u32, u32, u32, u32) {
    let mut eax = VMPORT_MAGIC;
    let mut ecx = command;
    let edx = VMPORT_PORT as u32;
    let mut esi = 0;
    let mut edi = 0;
    let mut ebx_val = ebx;

    unsafe {
        core::arch::asm!(
            "push rbx",
            "mov ebx, {0:e}",
            "in eax, dx",
            "mov {0:e}, ebx",
            "pop rbx",
            inout(reg) ebx_val,
            inout("eax") eax,
            inout("ecx") ecx,
            in("edx") edx,
            inout("esi") esi,
            inout("edi") edi,
        );
    }
    (eax, ebx_val, ecx, edx, esi, edi)
}

pub fn init_vmmouse() -> bool {
    vmport_in(VMPORT_CMD_VMMOUSE_COMMAND, VMMOUSE_READ_ID);

    let (status, ebx, _, _, _, _) = vmport_in(VMPORT_CMD_VMMOUSE_STATUS, 0);
    let count = status & 0xFFFF;
    if count == 0 {
        crate::debugln!("VMMouse: Not found (queue empty). Status={:#x} EBX={:#x}", status, ebx);
        return false;
    }

    let (version, _, _, _, _, _) = vmport_in(VMPORT_CMD_VMMOUSE_DATA, count);
    if version != 0x3442554a {
        crate::debugln!("VMMouse: Unsupported version {:#x}", version);
        return false;
    }

    vmport_in(VMPORT_CMD_VMMOUSE_COMMAND, VMMOUSE_REQUEST_ABSOLUTE);

    unsafe { VMMOUSE_ACTIVE = true; }
    true
}

const CMD_ENABLE_AUX: u8 = 0xA8;
const CMD_GET_COMPAQ_STATUS: u8 = 0x20;
const CMD_SET_COMPAQ_STATUS: u8 = 0x60;
const CMD_WRITE_AUX: u8 = 0xD4;

const MOUSE_RESET: u8 = 0xFF;
const MOUSE_SET_DEFAULTS: u8 = 0xF6;
const MOUSE_ENABLE_STREAMING: u8 = 0xF4;
const MOUSE_GET_ID: u8 = 0xF2;
const MOUSE_SET_SAMPLE_RATE: u8 = 0xF3;

pub fn init_mouse() {
    println!("Mouse: Initializing PS/2 Mouse...");

    wait_write();
    outb(0x64, CMD_ENABLE_AUX);

    wait_write();
    outb(0x64, CMD_GET_COMPAQ_STATUS);
    wait_read();
    let mut status = inb(0x60);
    status |= 2;
    status &= !0x20;
    wait_write();
    outb(0x64, CMD_SET_COMPAQ_STATUS);
    wait_write();
    outb(0x60, status);

    // Unmask IRQ 12 on slave PIC
    unsafe {
        (*(&raw const crate::interrupts::pic::PICS)).slave.unmask_irq(4);
    }

    if init_vmmouse() {
        println!("Mouse: VMMouse initialized successfully (Absolute Mode).");
    }

    mouse_write(MOUSE_SET_DEFAULTS);
    let _ack = mouse_read();

    mouse_write(MOUSE_ENABLE_STREAMING);
    let _ack = mouse_read();

    println!("Mouse: Initialized.");
}

fn mouse_write(value: u8) {
    wait_write();
    outb(0x64, CMD_WRITE_AUX);
    wait_write();
    outb(0x60, value);
}

fn mouse_read() -> u8 {
    wait_read();
    inb(0x60)
}

fn wait_write() {
    let mut timeout = 100_000;
    while timeout > 0 {
        if (inb(0x64) & 2) == 0 { return; }
        timeout -= 1;
    }
}

fn wait_read() {
    let mut timeout = 100_000;
    while timeout > 0 {
        if (inb(0x64) & 1) == 1 { return; }
        timeout -= 1;
    }
}

